#!/usr/bin/env python3
"""Pixel art for PrideChat's radios + devices (16x16, drawn as character grids)."""
from PIL import Image
import os

OUT = os.path.expanduser("~/mc-mods/pridechat/src/main/resources/assets/pridechat/textures")
P = {
    '.': None,
    'k': (24, 18, 34), 'd': (52, 44, 66), 'g': (92, 84, 110), 'l': (150, 142, 168), 'w': (230, 226, 240),
    'p': (245, 169, 184), 'b': (91, 206, 250), 'P': (176, 112, 255), 'r': (228, 3, 3), 'o': (255, 140, 0),
    'y': (255, 237, 0), 'G': (0, 128, 38), 'B': (36, 64, 142), 'v': (115, 41, 130), 'n': (124, 252, 154),
    's': (60, 60, 64), 'S': (110, 110, 118), 'i': (198, 198, 206), 'c': (40, 34, 52), 'm': (70, 60, 90),
}

def img(rows, name, folder):
    assert len(rows) == 16, (name, len(rows))
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        assert len(row) == 16, (name, y, row)
        for x, ch in enumerate(row):
            c = P[ch]
            if c: im.putpixel((x, y), c + (255,))
    im.save(os.path.join(OUT, folder, name + ".png"))

